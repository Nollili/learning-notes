import assert from 'node:assert/strict';
import { readSmallJson, InputError } from './lib/http-input';
import { parseRename } from './lib/note-input';
const make=(body:BodyInit|null,type='application/json')=>new Request('http://fixture.invalid/notes',{method:'POST',headers:{'Content-Type':type},body,duplex:'half'} as RequestInit);
assert.deepEqual(await readSmallJson(make('{"title":"Course"}')),{title:'Course'});
const status=(n:number)=>(e:unknown)=>e instanceof InputError&&e.status===n;
await assert.rejects(readSmallJson(make('{}','text/plain')),status(415));
await assert.rejects(readSmallJson(make(null)),status(400));
await assert.rejects(readSmallJson(make(new Uint8Array([255]))),status(400));
await assert.rejects(readSmallJson(make('{bad')),status(400));
await assert.rejects(readSmallJson(make('123456'),4),status(413));
let canceled=false;
const stalled=new ReadableStream<Uint8Array>({cancel(){canceled=true;}});
await assert.rejects(readSmallJson(make(stalled),4096,15),status(408));
assert.equal(canceled,true);
const id='00000000-0000-4000-8000-000000000001';
assert.deepEqual(parseRename({id,title:' Course ',version:1}),{id,title:'Course',version:1});
for(const input of [null,[],{id,title:'',version:1},{id,title:'Course',version:0},{id,title:'Course',version:1,userId:'forged'}])assert.equal(parseRename(input),null);
console.log('Pure Next boundary: JSON/UTF8/type/byte/deadline/cancel and strict mutation-input cases passed. No DB/auth integration.');
